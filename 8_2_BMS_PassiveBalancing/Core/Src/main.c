/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_I2C1_Init();
  MX_USART2_UART_Init();
  /* USER CODE BEGIN 2 */
  if (BQ76920_Init(&hi2c1) != HAL_OK || BAL_Detect(&pack) != HAL_OK)
  {
    while (1)                                   /* repeat, so a late Hercules still sees it */
    {
      send("BMS init failed\r\n");
      HAL_Delay(1000);
    }
  }
#if BLEED_TEST
  send("Bleed test: Cell2 on for 20 s, measure now\r\n");
  BQ76920_SetBalance(0x02);                     /* CB2 = chip input VC2 */
  HAL_Delay(20000);
  BAL_Read(&pack);
  print_cells("  (read while bleeding Cell2)");
  BQ76920_SetBalance(0);
  send("Bleed test done\r\n");
  HAL_Delay(2000);
  BAL_Read(&pack);
#endif
  snprintf(buf, sizeof(buf), "%u cells found\r\n", pack.count);
  send(buf);
  print_cells("");                              /* voltage of every cell */
  send("Starting balancing\r\n");
  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
    HAL_Delay(1000);                            /* one step per second */

    if (state == BAL_RUNNING)
    {
      state = BAL_Tick(&pack);                  /* 4 s bleeding, 1 s rest, until balanced */
      if (state == BAL_RUNNING)
      {
        char tail[64] = "  resting";
        if (pack.bleed != 0)
        {
          int t = snprintf(tail, sizeof(tail), "  bleeding:");
          for (uint8_t k = 0; k < pack.count; k++)
          {
            if (pack.bleed & (1U << pack.input[k]))
            {
              t += snprintf(tail + t, sizeof(tail) - t, " Cell%u", k + 1);
            }
          }
          uint8_t cb = 0;                       /* read CELLBAL1 back to see what the chip holds */
          BQ76920_ReadReg(0x01, &cb);
          snprintf(tail + t, sizeof(tail) - t, " (CELLBAL1=0x%02X)", cb);
        }
        print_cells(tail);
      }
      else if (state == BAL_DONE)
      {
        send("Finish balancing\r\n");
      }
      else
      {
        send("I2C error, balancing stopped\r\n");
      }
    }
    else if (state == BAL_DONE)
    {
      if (BAL_Read(&pack) == HAL_OK)            /* keep showing the cells and the pack total */
      {
        uint32_t total = 0;
        for (uint8_t k = 0; k < pack.count; k++) total += pack.mv[k];
        char tail[32];
        snprintf(tail, sizeof(tail), "  Pack=%lu mV", (unsigned long)total);
        print_cells(tail);
      }
    }
  }
  /* USER CODE END 3 */
}

