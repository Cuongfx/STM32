static void send(const char *s)
{
  HAL_UART_Transmit(&huart2, (uint8_t *)s, strlen(s), HAL_MAX_DELAY);
}

/* Print "Cell1=... Cell2=... mV" followed by tail text and a new line. */
static void print_cells(const char *tail)
{
  int n = 0;
  for (uint8_t k = 0; k < pack.count; k++)
  {
    n += snprintf(buf + n, sizeof(buf) - n, "Cell%u=%u ", k + 1, pack.mv[k]);
  }
  snprintf(buf + n, sizeof(buf) - n, "mV%s\r\n", tail);
  send(buf);
}
