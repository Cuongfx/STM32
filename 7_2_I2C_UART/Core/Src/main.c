    {
      handle_command(line);
    }

    if (DS3231_GetTime(&now) == HAL_OK && now.second != last_second)
    {
      last_second = now.second;
      CH340G_Printf("%02d/%02d/%04d %02d:%02d:%02d\r\n",
                    now.date, now.month, 2000 + now.year,
                    now.hour, now.minute, now.second);
    }
